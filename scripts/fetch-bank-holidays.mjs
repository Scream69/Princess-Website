/*
 * Refreshes src/data/bank-holidays.json from GOV.UK's official feed.
 *
 * The client is closed on bank holidays, so the drop-off slot picker must not
 * offer one. The dates are a published fact with an authoritative free source,
 * and inventing or hand-typing them would be exactly the kind of business fact
 * CLAUDE.md 12 forbids guessing at.
 *
 * Run by hand, not at build time (`npm run fetch:holidays`). A build that
 * fails because gov.uk is down is a far worse trade than a data file that is
 * refreshed once a year. The picker looks six months ahead
 * (`repairs.json`'s `slots.daysAhead`), so this cannot be left indefinitely —
 * the warning below is real, not decorative. Documented in the README
 * beside check-links.
 *
 * England and Wales only: the shop is in Edgware. Scotland and Northern
 * Ireland have different dates, and picking the wrong division would close the
 * counter on a day it is open.
 */
import { writeFile } from 'node:fs/promises';

const SOURCE = 'https://www.gov.uk/bank-holidays.json';
const DIVISION = 'england-and-wales';
const OUT = new URL('../src/data/bank-holidays.json', import.meta.url);

const response = await fetch(SOURCE, {
  headers: { Accept: 'application/json' },
  signal: AbortSignal.timeout(15000),
});

if (!response.ok) {
  console.error(`✗ ${SOURCE} answered ${response.status}`);
  process.exit(1);
}

const body = await response.json();
const events = body?.[DIVISION]?.events;

if (!Array.isArray(events) || events.length === 0) {
  console.error(`✗ no "${DIVISION}" events in the response — has the feed changed shape?`);
  process.exit(1);
}

/*
 * Dates only, and only ones still ahead of us. The feed carries a title and a
 * couple of flags per entry and none of it is read: the picker asks one
 * question of this list — is the shop shut on this date — and this file is
 * imported into the browser bundle, where the 2019 dates are pure weight.
 */
const today = new Date().toISOString().slice(0, 10);
const dates = [...new Set(events.map((event) => event.date))]
  .filter((date) => date && date >= today)
  .sort();

const file = {
  _comment:
    'Generated by scripts/fetch-bank-holidays.mjs from https://www.gov.uk/bank-holidays.json ' +
    '(england-and-wales). Do not edit by hand — re-run `npm run fetch:holidays`. ' +
    'For one-off closures the client sets themselves, use `closures` in site.json.',
  division: DIVISION,
  fetchedAt: new Date().toISOString().slice(0, 10),
  dates,
};

await writeFile(OUT, `${JSON.stringify(file, null, 2)}\n`, 'utf8');

const last = dates.at(-1);
console.log(`✓ ${dates.length} bank holidays written, ${dates[0]} to ${last}`);

/*
 * The feed runs out eventually — it publishes roughly three years at a time.
 * Say so plainly rather than letting the picker quietly start offering days
 * the shop is closed once the list is overtaken.
 */
const monthsLeft = (new Date(last) - Date.now()) / (1000 * 60 * 60 * 24 * 30);
if (monthsLeft < 12) {
  console.warn(`! only ${Math.round(monthsLeft)} months of data left — re-run this before ${last}`);
}
